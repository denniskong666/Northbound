        public static string Resolve(string dialogueId, int lineIndex, string english, string explicitChinese)
        {
            if (!GameText.IsChinese) return english ?? string.Empty;
            if (!string.IsNullOrWhiteSpace(explicitChinese)) return explicitChinese;
            return Lines.TryGetValue(dialogueId ?? string.Empty, out var lines) &&
                lineIndex >= 0 && lineIndex < lines.Length && !string.IsNullOrWhiteSpace(lines[lineIndex])
                    ? lines[lineIndex]
                    : english ?? string.Empty;
        }

        public static bool HasTranslation(string dialogueId, int lineIndex, string explicitChinese)
        {
            if (!string.IsNullOrWhiteSpace(explicitChinese)) return true;
            return Lines.TryGetValue(dialogueId ?? string.Empty, out var lines) &&
                lineIndex >= 0 && lineIndex < lines.Length && !string.IsNullOrWhiteSpace(lines[lineIndex]);
        }
